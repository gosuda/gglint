// The automatic-write gate: `run -fix` applies admitted in-module fixes,
// refuses the rest with a message, and leaves refused files byte-identical.

func TestFixSecondRunChangesNothing(t *testing.T) {
	t.Parallel()
	dir := workspace(t, "")
	before := readFile(t, filepath.Join(dir, "i", "i.go"))
	first := gglint(t, dir, "run", "-fix", "./i")
	assertResult(t, first, result{stdout: agentSummary(0, 0, "")})
	fixed := readFile(t, filepath.Join(dir, "i", "i.go"))
	if fixed == before {
		t.Fatal("first -fix left i/i.go unchanged")
	}
	second := gglint(t, dir, "run", "-fix", "./i")
	assertResult(t, second, result{stdout: agentSummary(0, 0, "")})
	if again := readFile(t, filepath.Join(dir, "i", "i.go")); again != fixed {
		t.Fatalf("second -fix changed i/i.go:\nfirst:  %q\nsecond: %q", fixed, again)
	}
	assertResult(t, gglint(t, dir, "run", "./i"), result{stdout: agentSummary(0, 0, "")})
}

func TestFixRefusesGeneratedFileWithMessage(t *testing.T) {
	t.Parallel()
	dir := workspace(t, "")
	const generated = "// Code generated by hand. DO NOT EDIT.\n\npackage gf\n\nfunc F() int {\n\n\treturn 1\n}\n"
	pkg := filepath.Join(dir, "gf")
	if err := os.Mkdir(pkg, 0o750); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(pkg, "gf.go"), generated)
	want := result{
		stdout: agentSummary(0, 0, ""),
		stderr: "gglint: refused gf/gf.go: generated file\n",
	}
	env := childEnv(t, dir)
	for range 2 {
		assertResult(t, gglintEnv(t, dir, env, "run", "-fix", "./gf"), want)
	}
	if got := readFile(t, filepath.Join(pkg, "gf.go")); got != generated {
		t.Fatalf("generated file changed:\n got: %q\nwant: %q", got, generated)
	}
	assertResult(t, gglint(t, dir, "run", "./gf"), result{stdout: agentSummary(0, 0, "")})
}

func TestFixRefusesTestsOffFileWithMessage(t *testing.T) {
	t.Parallel()
	const testsOff = "[run]\ntests = false\n"
	dir := workspace(t, "")
	before := readFile(t, filepath.Join(dir, "fixtests", "f.go"))
	writeFile(t, filepath.Join(dir, config.FileName), testsOff)
	testBefore := readFile(t, filepath.Join(dir, "fixtests", "f_test.go"))
	got := gglint(t, dir, "run", "-format", "text", "-fix", "./fixtests")
	want := result{stderr: configLine(testsOff) + "gglint: refused fixtests/f_test.go: test file excluded when tests are off\n"}
	assertResult(t, got, want)
	if fixed := readFile(t, filepath.Join(dir, "fixtests", "f.go")); fixed == before {
		t.Fatal("fixtests/f.go was not fixed")
	}
	if after := readFile(t, filepath.Join(dir, "fixtests", "f_test.go")); after != testBefore {
		t.Fatalf("fixtests/f_test.go changed with tests = false:\n got: %q\nwant: %q", after, testBefore)
	}
}

func TestCheckimportsDenialIsDiagnosticOnly(t *testing.T) {
	t.Parallel()
	toml := "mode = \"basic\"\n\n[rules.checkimports]\ndeny = [{ path = \"strings\" }]\n"
	dir := workspace(t, toml)
	pkg := filepath.Join(dir, "im")
	if err := os.Mkdir(pkg, 0o750); err != nil {
		t.Fatal(err)
	}
	const src = "package im\n\nimport \"strings\"\n\nvar Trim = strings.TrimSpace\n"
	writeFile(t, filepath.Join(pkg, "im.go"), src)

	type finding struct {
		Rule    string   `json:"rule"`
		Path    string   `json:"path"`
		Line    int      `json:"line"`
		Fixes   []string `json:"fixes"`
		Fixable bool     `json:"fixable"`
	}
	type report struct {
		Findings []finding `json:"findings"`
	}
	got := gglint(t, dir, "run", "-format", "json", "./im")
	if got.code != 1 || got.stderr != configLine(toml) {
		t.Fatalf("exit %d, stderr %q; want exit 1, stderr %q", got.code, got.stderr, configLine(toml))
	}
	var doc report
	if err := json.Unmarshal([]byte(got.stdout), &doc); err != nil {
		t.Fatalf("decode %q: %v", got.stdout, err)
	}
	if len(doc.Findings) != 1 || doc.Findings[0].Rule != "checkimports" {
		t.Fatalf("findings = %+v, want one checkimports finding", doc.Findings)
	}
	if f := doc.Findings[0]; len(f.Fixes) != 0 || f.Fixable {
		t.Fatalf("checkimports finding carries a fix: %+v", f)
	}
	agent := gglint(t, dir, "run", "./im")
	if agent.code != 1 || strings.Contains(agent.stdout, "fix:") {
		t.Fatalf("agent output = %q, want a finding with no fix: suffix", agent.stdout)
	}
	fixed := gglint(t, dir, "run", "-fix", "./im")
	if fixed.code != 1 || strings.Contains(fixed.stderr, "refused") {
		t.Fatalf("-fix exit %d, stderr %q; want exit 1 with no refusal", fixed.code, fixed.stderr)
	}
	if after := readFile(t, filepath.Join(pkg, "im.go")); after != src {
		t.Fatalf("denied import file changed:\n got: %q\nwant: %q", after, src)
	}
}

func TestTypeErrorLeavesDiagnosticWithoutFix(t *testing.T) {
	t.Parallel()
	dir := workspace(t, "")
	pkg := filepath.Join(dir, "x")
	if err := os.Mkdir(pkg, 0o750); err != nil {
		t.Fatal(err)
	}
	// A semantic error gofumpt cannot see: the file is already formatted,
	// so gofumpt stays silent while typecheck reports a diagnostic that
	// carries no fix.
	const broken = "package x\n\nfunc Broken() int {\n\treturn \"s\"\n}\n"
	writeFile(t, filepath.Join(pkg, "x.go"), broken)
	got := gglint(t, dir, "run", "-format", "json", "./x")
	if got.code != 1 || got.stderr != "" {
		t.Fatalf("exit %d, stderr %q; want exit 1, empty stderr", got.code, got.stderr)
	}
	if strings.Contains(got.stdout, `"rule":"gofumpt"`) {
		t.Fatalf("gofumpt reported on a semantically broken file: %s", got.stdout)
	}
	if !strings.Contains(got.stdout, `"rule":"typecheck"`) {
		t.Fatalf("no typecheck diagnostic for a semantically broken file: %s", got.stdout)
	}
	if strings.Contains(got.stdout, `"fixable":true`) || strings.Contains(got.stdout, `"fixes"`) {
		t.Fatalf("broken file finding carries a fix: %s", got.stdout)
	}
	fixed := gglint(t, dir, "run", "-fix", "./x")
	if fixed.code != 1 || fixed.stderr != "" {
		t.Fatalf("-fix exit %d, stderr %q; want exit 1, empty stderr", fixed.code, fixed.stderr)
	}
	if after := readFile(t, filepath.Join(pkg, "x.go")); after != broken {
		t.Fatalf("broken file changed:\n got: %q\nwant: %q", after, broken)
	}
}

func TestFixContractDocumented(t *testing.T) {
	t.Parallel()
	got := gglint(t, t.TempDir(), "run", "-h")
	if got.code != 2 {
		t.Fatalf("exit %d, want 2 for -h", got.code)
	}
	for _, want := range []string{"-fix", "refuse"} {
		if !strings.Contains(got.stderr, want) {
			t.Fatalf("-h output %q does not mention %q", got.stderr, want)
		}
	}
	data, err := os.ReadFile(filepath.Join("..", "..", "README.md"))
	if err != nil {
		t.Fatal(err)
	}
	readme := string(data)
	for _, want := range []string{
		"Automatic fixes",
		"outside the analysis scope",
		"generated file",
		"test file excluded when tests are off",
		"does not parse after fix",
		"changed without an applied fix",
	} {
		if !strings.Contains(readme, want) {
			t.Fatalf("README does not state %q", want)
		}
	}
}

const modernizeOnly = "mode = \"basic\"\nenable = [\"modernize\"]\ndisable = [\"gofumpt\", \"gosimple\", \"misspell\", \"usetesting\"]\n"

const multilineAtomic = "package counter\n\nimport \"sync/atomic\"\n\nvar count int32\n\nfunc Read() int32 {\n\treturn atomic.LoadInt32(\n\t\t&count,\n\t)\n}\n"

func TestFixKeepsAtomicGroupWhenTestsAreExcluded(t *testing.T) {
	t.Parallel()
	dir := workspace(t, modernizeOnly+"[run]\ntests = false\n")
	pkg := filepath.Join(dir, "counter")
	if err := os.Mkdir(pkg, 0o750); err != nil {
		t.Fatal(err)
	}
	const production = "package counter\n\nvar count int32\n"
	const testSource = "package counter\n\nimport (\n\t\"sync/atomic\"\n\t\"testing\"\n)\n\nfunc TestCounter(t *testing.T) {\n\tif atomic.LoadInt32(&count) != 0 {\n\t\tt.Fatal(\"nonzero counter\")\n\t}\n}\n"
	writeFile(t, filepath.Join(pkg, "counter.go"), production)
	writeFile(t, filepath.Join(pkg, "counter_test.go"), testSource)
	got := gglint(t, dir, "run", "-fix", "./counter")
	if got.code != 1 || !strings.Contains(got.stderr, "counter/counter_test.go: test file excluded when tests are off") || !strings.Contains(got.stdout, "modernize") {
		t.Fatalf("atomic group result = %+v", got)
	}
	if readFile(t, filepath.Join(pkg, "counter.go")) != production || readFile(t, filepath.Join(pkg, "counter_test.go")) != testSource {
		t.Fatal("a refused atomic group changed one of its files")
	}
	check := exec.CommandContext(t.Context(), "go", "test", "-run", "^$", "./counter")
	check.Dir, check.Env = dir, childEnv(t, dir)
	if output, err := check.CombinedOutput(); err != nil {
		t.Fatalf("refused package no longer compiles: %v\n%s", err, output)
	}
}

func TestFixRefusesInvalidSiblingRewriteAndStillReports(t *testing.T) {
	t.Parallel()
	dir := workspace(t, modernizeOnly)
	for _, name := range []string{"neighbor", "counter"} {
		if err := os.Mkdir(filepath.Join(dir, name), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	writeFile(t, filepath.Join(dir, "neighbor/neighbor.go"), "package neighbor\n")
	path := filepath.Join(dir, "counter/counter.go")
	writeFile(t, path, multilineAtomic)
	got := gglint(t, filepath.Join(dir, "neighbor"), "run", "-fix", "../counter")
	if got.code != 1 || !strings.Contains(got.stderr, "gglint: refused ../counter/counter.go: does not parse after fix") || !strings.Contains(got.stdout, "modernize") {
		t.Fatalf("sibling refusal result = %+v", got)
	}
	if after := readFile(t, path); after != multilineAtomic {
		t.Fatalf("invalid sibling rewrite survived: %q", after)
	}
}

func TestFixConflictLeavesOtherPackageUnchanged(t *testing.T) {
	t.Parallel()
	dir := workspace(t, "")
	for _, name := range []string{"conflict", "counter"} {
		if err := os.Mkdir(filepath.Join(dir, name), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	const conflicting = "package conflict\n\n// F stores an adress.\nfunc F( ) int {return 1}\n"
	path := filepath.Join(dir, "counter/counter.go")
	writeFile(t, filepath.Join(dir, "conflict/conflict.go"), conflicting)
	writeFile(t, path, multilineAtomic)
	got := gglint(t, dir, "run", "-fix", "./conflict", "./counter")
	if got.code != 3 || !strings.Contains(got.stderr, "conflict") {
		t.Fatalf("fix conflict result = %+v", got)
	}
	if after := readFile(t, path); after != multilineAtomic {
		t.Fatalf("another package's fix escaped a failed run: %q", after)
	}
	if after := readFile(t, filepath.Join(dir, "conflict/conflict.go")); after != conflicting {
		t.Fatalf("conflicting source changed: %q", after)
	}
}

func TestTargetedFixIgnoresUnreadableUnselectedDirectory(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("requires Unix permission enforcement for an ordinary user")
	}
	dir := workspace(t, "")
	blocked := filepath.Join(dir, "container-data")
	if err := os.Mkdir(blocked, 0o700); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(blocked, "hidden.go"), "package hidden\n")
	if err := os.Chmod(blocked, 0); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(blocked, 0o700) })
	before := readFile(t, filepath.Join(dir, "i/i.go"))
	got := gglint(t, dir, "run", "-fix", "./i")
	if got.code != 0 || strings.Contains(got.stderr, "cannot snapshot") {
		t.Fatalf("targeted fix result = %+v", got)
	}
	if after := readFile(t, filepath.Join(dir, "i/i.go")); after == before {
		t.Fatal("selected ordinary fix did not run")
	}
}

func TestFixCLIAccountsForUnrecordedWrite(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("the controlled Go wrapper requires a POSIX shell")
	}
	dir := workspace(t, modernizeOnly)
	pkg := filepath.Join(dir, "stale")
	if err := os.Mkdir(pkg, 0o750); err != nil {
		t.Fatal(err)
	}
	const before = "package stale\n\nfunc Value() int { return 1 }\n"
	path := filepath.Join(pkg, "stale.go")
	writeFile(t, path, before)
	realGo, err := exec.LookPath("go")
	if err != nil {
		t.Fatal(err)
	}
	wrapper := t.TempDir()
	const script = "#!/bin/sh\nfor arg do\n  case \"$arg\" in\n    -fix|-fix-output=*) printf 'package stale\\n\\nfunc Value() int { return 7 }\\n' > \"$GGLINT_TEST_TARGET\" ;;\n  esac\ndone\nexec \"$GGLINT_TEST_GO\" \"$@\"\n"
	if err := os.WriteFile(filepath.Join(wrapper, "go"), []byte(script), 0o700); err != nil {
		t.Fatal(err)
	}
	env := append(childEnv(t, dir),
		"PATH="+wrapper+string(os.PathListSeparator)+os.Getenv("PATH"),
		"GGLINT_TEST_GO="+realGo,
		"GGLINT_TEST_TARGET="+path,
	)
	got := gglintEnv(t, dir, env, "run", "-fix", "./stale")
	if got.code != 0 || !strings.Contains(got.stderr, "gglint: refused stale/stale.go: changed without an applied fix") || got.stdout == "" {
		t.Fatalf("unrecorded write result = %+v", got)
	}
	if after := readFile(t, path); after != before {
		t.Fatalf("unrecorded source change survived: %q", after)
	}
}
