package driver_test

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/gosuda/gglint/internal/driver"
)

// fileMode reports the permission bits the platform records for path. Go
// reports a coarse mode on Windows (writable files read back as 0666), so
// the tests below compare the recorded mode before and after instead of
// asserting one literal: preservation is the invariant on every platform.
func fileMode(t *testing.T, path string) os.FileMode {
	t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	return info.Mode().Perm()
}

func TestApplyPreservesPermissionBits(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	path := filepath.Join(dir, "a", "a.go")
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}
	before := fileMode(t, path)
	pre := snapshot(t, dir)
	changed := strings.Replace(plainMain, "return 1", "return 2", 1)
	if violations, err := driver.ApplyFixed(dir, pre, map[string][]byte{"a/a.go": []byte(changed)}, true); err != nil || len(violations) != 0 {
		t.Fatalf("ApplyFixed = %v, %v; want the admitted fix published", violations, err)
	}
	if got := readFile(t, path); got != changed {
		t.Fatalf("after publish = %q, want the fixed bytes", got)
	}
	if got := fileMode(t, path); got != before {
		t.Fatalf("mode = %o, want the recorded %o", got, before)
	}
}

func TestUndoRestoresBytesAndPermissionBits(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	gen := "// Code generated by hand. DO NOT EDIT.\n\n" + plainMain
	writeGo(t, dir, "a/a.go", gen)
	path := filepath.Join(dir, "a", "a.go")
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}
	before := fileMode(t, path)
	pre := snapshot(t, dir)
	changed := "// Code generated by hand. DO NOT EDIT.\n\n" + strings.Replace(plainMain, "return 1", "return 2", 1)
	writeGo(t, dir, "a/a.go", changed)
	violations := driver.VerifyFixed(dir, pre, map[string]bool{"a/a.go": true}, true)
	if want := []string{"a/a.go: " + driver.ViolateGen}; !slices.Equal(violationPaths(violations), want) {
		t.Fatalf("violations = %v, want %v", violationPaths(violations), want)
	}
	if err := violations[0].Undo(dir); err != nil {
		t.Fatalf("undo: %v", err)
	}
	if got := readFile(t, path); got != gen {
		t.Fatalf("after undo = %q, want the pre-fix bytes", got)
	}
	if got := fileMode(t, path); got != before {
		t.Fatalf("mode = %o, want the recorded %o", got, before)
	}
}
