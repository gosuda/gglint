func writeGo(t *testing.T, dir, rel, body string) {
	t.Helper()
	path := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

const plainMain = "package p\n\nfunc F() int {\n\treturn 1\n}\n"

func snapshot(t *testing.T, dir string) driver.GoSnapshot {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(dir, "a", "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	snap, err := driver.SnapshotGoFiles(dir, files...)
	if err != nil {
		t.Fatalf("snapshot: %v", err)
	}
	t.Cleanup(func() {
		if err := snap.Close(); err != nil {
			t.Error(err)
		}
	})
	return snap
}

func violationPaths(vs []driver.FixViolation) []string {
	out := make([]string, 0, len(vs))
	for _, v := range vs {
		out = append(out, v.Path+": "+v.Reason)
	}
	slices.Sort(out)
	return out
}

func TestSnapshotReadsOnlySelectedGoFiles(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	writeGo(t, dir, "a/note.txt", "x")
	writeGo(t, dir, ".git/hooks/a.go", plainMain)
	snap := snapshot(t, dir)
	if len(snap) != 1 || snap["a/a.go"].Bytes == nil {
		t.Fatalf("snapshot keys = %v, want [a/a.go]", slices.Sorted(maps.Keys(snap)))
	}
	if got := string(snap["a/a.go"].Bytes); got != plainMain {
		t.Fatalf("snapshot bytes = %q, want %q", got, plainMain)
	}
}

