func TestVerifyRefusesGeneratedChangeAndRestores(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	gen := "// Code generated by hand. DO NOT EDIT.\n\n" + plainMain
	writeGo(t, dir, "a/a.go", gen)
	pre := snapshot(t, dir)
	writeGo(t, dir, "a/a.go", gen+"\n")
	got := driver.VerifyFixed(dir, pre, map[string]bool{"a/a.go": true}, true)
	if want := []string{"a/a.go: " + driver.ViolateGen}; !slices.Equal(violationPaths(got), want) {
		t.Fatalf("violations = %v, want %v", violationPaths(got), want)
	}
	if err := got[0].Undo(dir); err != nil {
		t.Fatalf("undo: %v", err)
	}
	if data, err := os.ReadFile(filepath.Join(dir, "a", "a.go")); err != nil {
		t.Fatalf("read after undo: %v", err)
	} else if string(data) != gen {
		t.Fatalf("after undo = %q, want the pre-fix bytes", data)
	}
}

