func TestVerifyRefusesCreatedAndDeletedPaths(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeGo(t, dir, "a/keep.go", plainMain)
	writeGo(t, dir, "a/gone.go", plainMain)
	pre := snapshot(t, dir)
	writeGo(t, dir, "a/new.go", plainMain)
	if err := os.Remove(filepath.Join(dir, "a", "gone.go")); err != nil {
		t.Fatal(err)
	}
	got := driver.VerifyFixed(dir, pre, nil, true)
	if want := []string{"a/gone.go: " + driver.ViolateDeleted, "a/new.go: " + driver.ViolateCreated}; !slices.Equal(violationPaths(got), want) {
		t.Fatalf("violations = %v, want %v", violationPaths(got), want)
	}
	for _, v := range got {
		if err := v.Undo(dir); err != nil {
			t.Fatalf("undo %s: %v", v.Path, err)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, "a", "new.go")); !os.IsNotExist(err) {
		t.Fatal("created file survived undo")
	}
	if data, err := os.ReadFile(filepath.Join(dir, "a", "gone.go")); err != nil || string(data) != plainMain {
		t.Fatalf("deleted file after undo = %q, %v; want the pre-fix bytes", data, err)
	}
}

func TestRefusalsExtractsOnlyRefusalLines(t *testing.T) {
	t.Parallel()
	stderr := []byte("# m/a\n./a.go:1:2: undefined: x\n" +
		"gglint: refused a/gen.go: generated file\r\n" +
		"gglint: other noise\n" +
		"gglint: refused b/b_test.go: test file excluded when tests are off\n")
	got := driver.Refusals(stderr)
	want := []string{
		"gglint: refused a/gen.go: generated file",
		"gglint: refused b/b_test.go: test file excluded when tests are off",
	}
	if !slices.Equal(got, want) {
		t.Fatalf("refusals = %q, want %q", got, want)
	}
	if got := driver.Refusals(nil); len(got) != 0 {
		t.Fatalf("refusals of empty stderr = %q, want none", got)
	}
}

