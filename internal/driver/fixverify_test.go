func TestApplyRejectsWholeBatchBeforeWriting(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	writeGo(t, dir, "a/b.go", "package p\n\nvar B = 1\n")
	pre := snapshot(t, dir)
	fixed := map[string][]byte{
		filepath.Join(dir, "a/a.go"): []byte(strings.Replace(plainMain, "return 1", "return 2", 1)),
		filepath.Join(dir, "a/b.go"): []byte("package p\n\nvar B = (\n"),
	}
	violations, err := driver.ApplyFixed(dir, pre, fixed, true)
	if err != nil || len(violations) != 1 || violations[0].Reason != driver.ViolateParse {
		t.Fatalf("ApplyFixed = %v, %v", violations, err)
	}
	if got := readFile(t, filepath.Join(dir, "a/a.go")); got != plainMain {
		t.Fatalf("valid half of a refused batch changed: %q", got)
	}
	if got := readFile(t, filepath.Join(dir, "a/b.go")); got != "package p\n\nvar B = 1\n" {
		t.Fatalf("invalid half of a refused batch changed: %q", got)
	}
}

func TestApplyAccountsForSelectedSibling(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	generated := "// Code generated by hand. DO NOT EDIT.\n\n" + plainMain
	writeGo(t, dir, "b/b.go", generated)
	work := filepath.Join(dir, "a")
	pre, err := driver.SnapshotGoFiles(work, filepath.Join(dir, "a/a.go"), filepath.Join(dir, "b/b.go"))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = pre.Close() }()
	violations, err := driver.ApplyFixed(work, pre, map[string][]byte{filepath.Join(dir, "b/b.go"): []byte(generated + "\n")}, true)
	if err != nil || len(violations) != 1 || violations[0].Path != "../b/b.go" || violations[0].Reason != driver.ViolateGen {
		t.Fatalf("ApplyFixed = %v, %v", violations, err)
	}
	if got := readFile(t, filepath.Join(dir, "b/b.go")); got != generated {
		t.Fatalf("selected sibling changed: %q", got)
	}
}

func TestRestoreDoesNotFollowSwappedLeafSymlink(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("Unix symlink attack; Windows replacement is covered by native apply tests")
	}
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	outside := filepath.Join(t.TempDir(), "outside.go")
	if err := os.WriteFile(outside, []byte("outside unchanged\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	pre := snapshot(t, dir)
	path := filepath.Join(dir, "a/a.go")
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, path); err != nil {
		t.Fatal(err)
	}
	violations, err := driver.ApplyFixed(dir, pre, nil, true)
	if err != nil || len(violations) != 1 || violations[0].Reason != driver.ViolateStale {
		t.Fatalf("ApplyFixed = %v, %v", violations, err)
	}
	if got := readFile(t, outside); got != "outside unchanged\n" {
		t.Fatalf("outside target overwritten: %q", got)
	}
	if got := readFile(t, path); got != plainMain {
		t.Fatalf("source not restored: %q", got)
	}
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() {
		t.Fatalf("restored leaf = %v, %v", info, err)
	}
}

func TestRestoreUsesOpenedPackageAfterParentSwap(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("Unix directory rename and symlink attack")
	}
	dir := t.TempDir()
	writeGo(t, dir, "a/a.go", plainMain)
	outside := t.TempDir()
	if err := os.WriteFile(filepath.Join(outside, "a.go"), []byte("outside unchanged\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	pre := snapshot(t, dir)
	moved := filepath.Join(dir, "saved")
	if err := os.Rename(filepath.Join(dir, "a"), moved); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(dir, "a")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(moved, "a.go"), []byte("package p\nvar Broken = (\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	violations, err := driver.ApplyFixed(dir, pre, nil, true)
	if err != nil || len(violations) != 1 {
		t.Fatalf("ApplyFixed = %v, %v", violations, err)
	}
	if got := readFile(t, filepath.Join(outside, "a.go")); got != "outside unchanged\n" {
		t.Fatalf("outside directory overwritten: %q", got)
	}
	if got := readFile(t, filepath.Join(moved, "a.go")); got != plainMain {
		t.Fatalf("opened source not restored: %q", got)
	}
}
