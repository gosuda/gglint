package vettool

import (
	"go/token"
	"strings"
	"sync"
	"testing"

	"golang.org/x/tools/go/analysis"

	"github.com/gosuda/gglint/internal/config"
)

// editAt builds a diagnostic that carries a fix at pos.
func editAt(pos token.Pos) analysis.Diagnostic {
	return analysis.Diagnostic{
		Pos:     pos,
		Message: "probe finding",
		SuggestedFixes: []analysis.SuggestedFix{{
			Message:   "fix it",
			TextEdits: []analysis.TextEdit{{Pos: pos, End: pos, NewText: []byte("var Y = 1")}},
		}},
	}
}

// refusedEngine builds a test engine that records refusal lines in a
// test-owned buffer instead of the process stderr, so parallel tests never
// touch the global os.Stderr.
func refusedEngine(t *testing.T, fix bool) (*engine, *strings.Builder) {
	t.Helper()
	e := newTestEngine(t, config.Config{Mode: config.Standard})
	e.fix = fix
	var out strings.Builder
	e.err = &lockedWriter{out: &out}
	return e, &out
}

type lockedWriter struct {
	mu  sync.Mutex
	out *strings.Builder
}

func (w *lockedWriter) Write(p []byte) (int, error) {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.out.Write(p)
}

// keepOutcome runs keep and reports whether the diagnostic was kept along
// with the first refusal line recorded, if any.
func keepOutcome(t *testing.T, e *engine, pass *analysis.Pass, d analysis.Diagnostic) (kept bool, refusal string) {
	t.Helper()
	kept = e.keep(pass, probeRule(), "", d)
	out, ok := e.err.(*lockedWriter)
	if !ok {
		t.Fatal("engine does not record refusals in a test buffer")
	}
	for line := range strings.SplitSeq(strings.TrimRight(out.out.String(), "\n"), "\n") {
		if strings.HasPrefix(line, "gglint: refused ") {
			return kept, strings.TrimRight(line, "\r")
		}
	}
	return kept, ""
}

func TestRefuseEmitsMessageOnlyForFixRuns(t *testing.T) {
	t.Parallel()
	const src = "// Code generated by hand. DO NOT EDIT.\n\npackage p\n\nvar X = 1\n"
	pass := func() *analysis.Pass { return newPass(t, "/work/p/a.go", src, nil) }
	decl := func() token.Pos { return newPass(t, "/work/p/a.go", src, nil).Files[0].Decls[0].Pos() }

	t.Run("generated with edits refused in fix mode", func(t *testing.T) {
		t.Parallel()
		e, _ := refusedEngine(t, true)
		kept, line := keepOutcome(t, e, pass(), editAt(decl()))
		if kept {
			t.Fatal("keep = true for a generated fix, want false")
		}
		want := "gglint: refused /work/p/a.go: " + refuseGen
		if line != want {
			t.Fatalf("refusal = %q, want %q", line, want)
		}
	})
	t.Run("generated with edits silent in report mode", func(t *testing.T) {
		t.Parallel()
		e, out := refusedEngine(t, false)
		if e.keep(pass(), probeRule(), "", editAt(decl())) {
			t.Fatal("keep = true for a generated fix, want false")
		}
		if out.String() != "" {
			t.Fatalf("report run printed %q, want silence", out.String())
		}
	})
	t.Run("generated without edits never refused", func(t *testing.T) {
		t.Parallel()
		e, out := refusedEngine(t, true)
		d := analysis.Diagnostic{Pos: decl(), Message: "probe finding"}
		if e.keep(pass(), probeRule(), "", d) {
			t.Fatal("keep = true for a generated finding, want false")
		}
		if out.String() != "" {
			t.Fatalf("fix run printed %q for a fixless diagnostic, want silence", out.String())
		}
	})
}

func TestRefuseOutOfScopeFix(t *testing.T) {
	t.Parallel()
	e, _ := refusedEngine(t, true)
	pass := newPass(t, "/work/p/a.go", "package p\n\nvar X = 1\n", nil)
	outside := pass.Fset.AddFile("/elsewhere/o.go", -1, 32).Pos(0)
	kept, line := keepOutcome(t, e, pass, editAt(outside))
	if kept {
		t.Fatal("keep = true for an out-of-scope fix, want false")
	}
	want := "gglint: refused /elsewhere/o.go: " + refuseScope
	if line != want {
		t.Fatalf("refusal = %q, want %q", line, want)
	}
}

func TestRefuseTestsOffFix(t *testing.T) {
	t.Parallel()
	e, _ := refusedEngine(t, true)
	pass := newPass(t, "/work/p/a_test.go", "package p\n\nvar X = 1\n", nil)
	pos := pass.Files[0].Decls[0].Pos()
	kept, line := keepOutcome(t, e, pass, editAt(pos))
	if kept {
		t.Fatal("keep = true for a tests-off fix, want false")
	}
	want := "gglint: refused /work/p/a_test.go: " + refuseTests
	if line != want {
		t.Fatalf("refusal = %q, want %q", line, want)
	}
}

func TestSuppressedFixStaysSilent(t *testing.T) {
	t.Parallel()
	e, out := refusedEngine(t, true)
	src := "package p\n\nvar X = 1 //nolint:probe // reason\n"
	pass := newPass(t, "/work/p/a.go", src, nil)
	pos := pass.Files[0].Decls[0].Pos()
	if e.keep(pass, probeRule(), "", editAt(pos)) {
		t.Fatal("keep = true for a suppressed fix, want false")
	}
	if out.String() != "" {
		t.Fatalf("fix run printed %q for a suppressed fix, want silence", out.String())
	}
}

func TestWantFixArgs(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		args []string
		want bool
	}{
		{nil, false},
		{[]string{"-config=x", "-json"}, false},
		{[]string{"-config=x", "-fix"}, true},
		{[]string{"-config=x", "--fix"}, true},
		{[]string{"-config=x", "-fix=true"}, true},
		{[]string{"-config=x", "-o", "fix"}, false},
	} {
		if got := wantFix(tc.args); got != tc.want {
			t.Errorf("wantFix(%q) = %v, want %v", tc.args, got, tc.want)
		}
	}
}
